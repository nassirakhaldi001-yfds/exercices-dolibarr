	/**
	 * Overload the doActions function : replacing the parent's function with the one below
	 *
	 * @param	array<string,mixed>	$parameters		Hook metadata (context, etc...)
	 * @param	CommonObject		$object			The object to process (an invoice if you are in invoice module, a propale in propale's module, etc...)
	 * @param	?string				$action			Current action (if set). Generally create or edit or null
	 * @param	HookManager			$hookmanager	Hook manager propagated to allow calling another hook
	 * @return	int									Return integer < 0 on error, 0 on success, 1 to replace standard code
	 */
public function doActions($parameters, &$object, &$action, $hookmanager)
    {
        $error = 0;

        // --- EXERCICES 1 & 5 : Interception de la fiche commande ---
        if (in_array('ordercard', explode(':', $parameters['context']))) {
            // Exercice 1 : Action "Marquer comme urgent"
            if ($action == 'set_urgent') {
                $object->array_options['options_urgent'] = 1;
                $result = $object->insertExtraFields();

                if ($result >= 0) {
                    setEventMessages("La commande a été marquée comme urgente avec succès.", null, 'mesgs');
                } else {
                    setEventMessages($object->error, $object->errors, 'errors');
                }
            }

            // Exercice 5 : Action "Cloner la commande"
            if ($action == 'clone_custom_order') {
                require_once DOL_DOCUMENT_ROOT . '/commande/class/commande.class.php';

                $newObject = new Commande($hookmanager->db);
                $result = $newObject->createFrom($object);

                if ($result > 0) {
                    setEventMessages('Commande clonée avec succès', null, 'mesgs');
                    // dol_redirect gère proprement la session et le message
                    dol_redirect(DOL_URL_ROOT . "/commande/card.php?id=" . $result);
                } else {
                    setEventMessages('Erreur lors du clonage : ' . $newObject->error, null, 'errors');
                }
            }
        }

        // --- Ancien code (Tiers) ---
        $currentContext = !empty($parameters['currentcontext']) ? $parameters['currentcontext'] : '';
        if (in_array($currentContext, array('thirdpartycard', 'somecontext2'))) {
            if ($action == 'add' && !empty($_POST['client']) && $_POST['fournisseur'] == 1) {
                setEventMessages("Impossible de définir le statut fournisseur pour un client", null, "errors");
                return 1;
            }
        }

        return 0;
    }
